"""Generate skins/phatta/src/video/phatta-geometry.css from the plate measurements in build_assets.T.

Every number is a plate pixel (1x). Positions are relative to the live-video rectangle's top-left corner, because the
media container sits exactly on that rectangle; the skin multiplies them by --phatta-k (plate px -> CSS px).
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_assets import T, OUT

def fmt(v):
    return ('%.2f' % v).rstrip('0').rstrip('.')

TUNE = {
    'night': {'tm-fs': 23.5, 'tm-sep': 5, 'tm-dx': 3.2, 'tm-dy': 1.2, 'tag-fs': 11, 'rate-fs': 17},
    'day': {'tm-fs': 24.4, 'tm-sep': 5, 'tm-dx': 3.2, 'tm-dy': -0.6, 'tag-fs': 11.5, 'rate-fs': 17},
}

def theme_vars(name, c, m):
    vx, vy, vw, vh = c['video']
    tx, ty, tw, th = c['track']
    bcx, bcy = c['ball_c']
    v = {}
    v['plate-w'] = c['W']
    v['tx'] = tx - vx; v['ty'] = ty - vy; v['tw'] = tw; v['th'] = th
    bx, by, bw, bh = c['ball']
    v['bw'] = bw; v['bh'] = bh; v['bdx'] = bx - bcx; v['bdy'] = by - ty
    cx_, cy_, cw, ch = c['chip']
    v['cw'] = cw; v['ch'] = ch; v['cdx'] = cx_ - bcx; v['cdy'] = cy_ - ty
    ctx, cty, ctw, cth = c['chip_text']
    v['ctx'] = ctx - cx_; v['cty'] = cty - cy_; v['ctw'] = ctw; v['cth'] = cth
    for b in ('play', 'vol', 'cc', 'rate', 'fs'):
        bx_, by_, r = c[b]
        ix, iy, iw, ih = c[b + '_icon']
        v[f'{b}-cx'] = bx_ - vx; v[f'{b}-cy'] = by_ - vy; v[f'{b}-d'] = 2 * r
        v[f'{b}-ix'] = ix - bx_; v[f'{b}-iy'] = iy - by_; v[f'{b}-iw'] = iw; v[f'{b}-ih'] = ih
    rp, rb = m['ring_play'], m['ring_btn']
    v['ring-play'] = rp['size']; v['ring-btn'] = rb['size']
    sx, sy, sw, sh = c['vslider']
    ax, ay, aw, ah = c['vtrack']
    kx, ky, kw, kh = c['vknob']
    v['vsx'] = ax - vx; v['vscy'] = ay + ah / 2 - vy; v['vsw'] = aw; v['vth'] = ah; v['kw'] = kw
    mx, my, mw, mh = c['time']
    v['tmx'] = mx - vx; v['tmy'] = my - vy; v['tmw'] = mw; v['tmh'] = mh
    lx, ly, lw, lh = m['capL']
    v['cap-w'] = lw; v['cap-h'] = lh; v['capR-w'] = m['capR'][2]
    st = c['strip']
    v['strip-w'] = st[2]; v['strip-h'] = st[3]
    v.update(TUNE[name])
    return v

def img(theme, name):
    base = f'../assets/{theme}/{name}'
    return f'image-set(url("{base}@1x.webp") 1x, url("{base}@2x.webp") 2x)'

def theme_block(theme, sel):
    I = lambda n: img(theme, n)
    return f"""
  {sel} {{
    & .media-time-slider-track {{ background-image: {I('silver')}; }}
    & .media-time-slider-fill {{ background-image: {I('gold')}; }}
    & .media-time-slider-thumb {{ background-image: {I('ball')}; }}
    & :is(.phatta-tag, .media-time-slider-preview-meta) {{ background-image: {I('chip')}; }}
    & .phatta-play::before {{ background-image: {I('play-icon')}; }}
    & .phatta-play:is([data-started]:not([data-paused]):not([data-ended]))::before {{ background-image: {I('pause-icon')}; }}
    & .media-mute-button:not([data-muted])::before {{ background-image: {I('vol-icon')}; }}
    & .media-captions-button::before {{ background-image: {I('cc-icon')}; }}
    & .media-fullscreen-button:not([data-fullscreen])::before {{ background-image: {I('fs-icon')}; }}
    & .media-volume-slider-track {{ background-image: {I('vsilver')}; }}
    & .media-volume-slider-fill {{ background-image: {I('vgold')}; }}
    & .media-volume-slider-thumb {{ background-image: {I('vknob')}; }}
    --phatta-ring-play: {I('ring-play')};
    --phatta-ring-btn: {I('ring-btn')};
    --phatta-strip: url("../assets/{theme}/strip@2x.webp");
    --phatta-capL: {I('capL')};
    --phatta-capR: {I('capR')};
  }}
"""

def main(dest):
    out = ['/* GENERATED by gen_css.py from the plate measurements; do not edit by hand.',
           '   Plate pixels (1x) relative to the live-video rectangle, scaled by --phatta-k. */',
           '@layer phatta {']
    for theme in ('night', 'day'):
        m = json.load(open(os.path.join(OUT, theme, 'meta.json')))
        v = theme_vars(theme, T[theme], m)
        sel = '.media-skin[data-skin="phatta"]' if theme == 'night' else ':where([data-phatta-theme="day"]) .media-skin[data-skin="phatta"]'
        out.append(f'  {sel} {{')
        for k, val in v.items():
            out.append(f'    --g-{k}: {fmt(val)};')
        out.append('  }')
        out.append(theme_block(theme, sel))
    out.append('}')
    open(dest, 'w').write('\n'.join(out) + '\n')

if __name__ == '__main__':
    main(sys.argv[1])
